"""Serve existing PoC results locally; no inference or app dependencies."""
import argparse
from functools import partial
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import urlsplit


class ReviewHandler(SimpleHTTPRequestHandler):
    def do_GET(self):
        if urlsplit(self.path).path == "/":
            self.send_response(302)
            self.send_header("Location", "/review.html")
            self.end_headers()
            return
        super().do_GET()

    def end_headers(self):
        # Review HTML may be regenerated by the background VLM job.
        self.send_header("Cache-Control", "no-cache")
        super().end_headers()

    def log_request(self, code="-", size="-"):
        if isinstance(code, int) and code >= 400:
            super().log_request(code, size)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--port", type=int, default=8765)
    args = parser.parse_args()
    if not 1 <= args.port <= 65535:
        parser.error("port must be between 1 and 65535")
    directory = Path(__file__).resolve().parent / "results"
    if not (directory / "review.html").is_file():
        parser.error("poc/results/review.html does not exist; generate the review first")
    handler = partial(ReviewHandler, directory=str(directory))
    try:
        with ThreadingHTTPServer(("127.0.0.1", args.port), handler) as server:
            print(f"OCR review: http://127.0.0.1:{args.port}/review.html", flush=True)
            print(f"Recognition only: http://127.0.0.1:{args.port}/page4_recognition_only/review.html", flush=True)
            print("Ctrl+C to stop. Serves poc/results only; no model/app startup.", flush=True)
            try:
                server.serve_forever()
            except KeyboardInterrupt:
                pass
    except OSError as exc:
        parser.exit(1, f"Cannot start review server: {exc}\n")


if __name__ == "__main__":
    main()
